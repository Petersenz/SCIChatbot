def format_answer(text):
    """Normalize plain-text lists, retaining all facts and missing-data notices."""
    text = (text or "").strip().replace("**", "")
    text = re.sub(r"(?m)^[ \t]*[*-][ \t]+", "• ", text)
    return re.sub(r"\n[ \t]*\n(?:[ \t]*\n)+", "\n\n", text)


